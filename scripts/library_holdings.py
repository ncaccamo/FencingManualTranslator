"""What you have, and where: the "Holdings" section of books/library.md.

Built from the files that actually exist, so it can't drift from them:
  original scan     books/<stem>.pdf, books/_skip/<stem>.pdf, else the gold
                    folder's copy (evals/gold/<stem>/src.pdf)
  English in hand   evals/gold/<stem>/ref.pdf (named from its meta.json), or
                    a print copy recorded in that meta.json
  this project      processed/<stem>_translated/*.pdf
Author / title / year / status come from the library tables below it.

    python3 scripts/library_holdings.py              # rewrite the Holdings section
    python3 scripts/library_holdings.py --export DIR # also copy everything to DIR
                                                     # with readable file names

Copyrighted translations (Crawley, Seager, Holzman, ...) are for your own
reading: the export is a private copy, like the repo's books/ and evals/.
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "books" / "library.md"
GOLD = ROOT / "evals" / "gold"
START, END = "<!-- holdings:start -->", "<!-- holdings:end -->"


def library_rows() -> dict:
    rows, cols = {}, []
    for raw in LIB.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("## "):
            cols = []
            continue
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if cells and cells[0].lower() == "stem":
            cols = [c.lower() for c in cells]
            continue
        m = re.match(r"`([a-z0-9_.-]+)`", cells[0]) if cells else None
        if not (m and cols and "title" in cols):
            continue
        row = dict(zip(cols, cells))
        clean = lambda s: re.sub(r"[*`]", "", s or "").strip()
        rows.setdefault(m.group(1), {
            "author": clean(row.get("author(s)", row.get("author", ""))),
            "title": clean(row.get("title", "")),
            "year": clean(row.get("year", "")),
            "status": clean(row.get("status", "")).lower(),
        })
    return rows


def gold_meta(stem: str) -> dict:
    p = GOLD / stem / "meta.json"
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def english_label(ref: dict) -> str:
    who = ref.get("translator") or ""
    title = ref.get("title") or ""
    year = f" ({ref['year']})" if ref.get("year") else ""
    return f"{who}, *{title}*{year}".strip(", ") if (who or title) else "English"


def holdings(rows: dict) -> list:
    stems = set()
    stems |= {p.stem for p in (ROOT / "books").glob("*.pdf")}
    stems |= {p.stem for p in (ROOT / "books" / "_skip").glob("*.pdf")}
    stems |= {p.name for p in GOLD.iterdir() if p.is_dir()}
    stems |= {p.name[:-len("_translated")] for p in (ROOT / "processed").glob("*_translated")
              if not p.name.endswith("_eval_translated")}
    out = []
    for s in sorted(stems):
        r = rows.get(s, {})
        orig = None
        for cand in (ROOT / "books" / f"{s}.pdf", ROOT / "books" / "_skip" / f"{s}.pdf",
                     GOLD / s / "src.pdf"):
            if cand.exists():
                orig = cand
                break
        meta = gold_meta(s)
        ref = meta.get("ref") or {}
        ref_pdf = GOLD / s / "ref.pdf"
        eng = None
        if ref_pdf.exists():
            partial = any("partial" in str(ref.get(k, "")).lower() for k in ("status", "source"))
            eng = ("file", ref_pdf, english_label(ref) + (" — partial scan" if partial else ""))
        elif ref:
            eng = ("print", None, english_label(ref) + " — " + (ref.get("status") or ref.get("source") or "owned"))
        proc = ROOT / "processed" / f"{s}_translated"
        ours = sorted(proc.glob("*English Only*.pdf")) + sorted(proc.glob("*Side by Side*.pdf")) if proc.exists() else []
        out.append({"stem": s, **r, "orig": orig, "eng": eng, "ours": ours,
                    "src_meta": meta.get("src") or {}})
    return out


def rel(p: Path) -> str:
    return str(p.relative_to(ROOT))


def group(h: dict) -> str:
    if h["ours"]:
        return "translated here"
    if h["eng"] and h["eng"][0] == "file":
        return "English in hand"
    if h["eng"]:
        return "English owned in print"
    return "original only"


def render(hs: list) -> str:
    L = [START, "## Holdings — what you have, and where",
         "",
         "_Generated by `scripts/library_holdings.py` from the files on disk — rerun it "
         "after adding a scan or translation; don't edit this section by hand. "
         "`--export DIR` copies everything to DIR with readable names._", ""]
    order = ["translated here", "English in hand", "English owned in print", "original only"]
    for g in order:
        rows = [h for h in hs if group(h) == g]
        if not rows:
            continue
        L += [f"### {g.capitalize()} ({len(rows)})", "",
              "| work | original scan | English | this project |", "|---|---|---|---|"]
        for h in sorted(rows, key=lambda h: (h.get("year") or str(h["src_meta"].get("year", "")), h["stem"])):
            title = h.get("title") or h["src_meta"].get("title", "")
            author = h.get("author") or h["src_meta"].get("author", "")
            year = h.get("year") or h["src_meta"].get("year", "")
            work = f"{author}, *{title}* ({year})<br>`{h['stem']}`"
            orig = f"`{rel(h['orig'])}`" if h["orig"] else "—"
            if h["eng"] and h["eng"][0] == "file":
                eng = f"{h['eng'][2]}<br>`{rel(h['eng'][1])}`"
            elif h["eng"]:
                eng = h["eng"][2]
            else:
                eng = "—"
            ours = "<br>".join(f"`{rel(p)}`" for p in h["ours"]) or "—"
            L.append(f"| {work} | {orig} | {eng} | {ours} |")
        L.append("")
    L.append(END)
    return "\n".join(L)


def write_section(text: str) -> None:
    lib = LIB.read_text(encoding="utf-8")
    if START in lib:
        lib = lib[:lib.index(START)] + text + lib[lib.index(END) + len(END):]
    else:  # first run: after the naming rules, before the first table section
        at = lib.index("\n---\n") + len("\n---\n")
        lib = lib[:at] + "\n" + text + "\n\n---\n" + lib[at:]
    LIB.write_text(lib, encoding="utf-8")


def safe(s: str) -> str:
    return re.sub(r'[\\/:*?"<>|]+', "-", re.sub(r"[*`]", "", s)).strip()


def export(hs: list, dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    n = 0
    for h in hs:
        title = h.get("title") or h["src_meta"].get("title", "") or h["stem"]
        author = h.get("author") or h["src_meta"].get("author", "")
        year = h.get("year") or h["src_meta"].get("year", "")
        key = "_".join(h["stem"].split("_")[:2])            # e.g. laboessiere_1818
        base = safe(f"{key} - {title} - {author}")[:150]
        items = []
        if h["orig"]:
            items.append((h["orig"], f"{base} - original.pdf"))
        if h["eng"] and h["eng"][0] == "file":
            who = safe(h["eng"][2].split(",")[0])
            items.append((h["eng"][1], f"{base} - English - {who}.pdf"))
        for p in h["ours"]:
            kind = "side by side" if "Side by Side" in p.name else "English"
            items.append((p, f"{base} - {kind} - this project.pdf"))
        for src, name in items:
            t = dest / name
            if not t.exists() or t.stat().st_mtime < src.stat().st_mtime:
                shutil.copy2(src, t)
                n += 1
    print(f"exported to {dest}: {n} file(s) copied or updated")


def main() -> None:
    hs = holdings(library_rows())
    write_section(render(hs))
    counts = {}
    for h in hs:
        counts[group(h)] = counts.get(group(h), 0) + 1
    print(f"Holdings section rewritten in {rel(LIB)}: {len(hs)} works {counts}")
    if "--export" in sys.argv:
        export(hs, Path(sys.argv[sys.argv.index("--export") + 1]).expanduser())


if __name__ == "__main__":
    main()
